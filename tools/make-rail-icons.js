/*
 * Rail icons, drawn rather than copied.
 *
 * The riven rune and the mod card are traced from the shapes the game uses - a triangle
 * inside a triangle inside a triangle, and a card with a torn foot - but redrawn for a 19px
 * box on a flat dark rail. The game's versions are photographs of inventory art, with
 * perspective, texture and a red cast from the mod background. Beside flat line icons that
 * reads as a smudge, not a shape.
 *
 * Drawn for the size they are actually used at, which is the part that is easy to get
 * wrong. The first pass used three nested triangles, 1.7px strokes and interior text lines.
 * Rendered at 19px the three triangles closed into a solid blob, the text lines vanished
 * into the background, and the whole thing read as a dark smudge - worse than the glyph it
 * replaced. Two triangles at 2.1px, and no interior detail, hold their shape.
 *
 * They are emitted as markup rather than files, and inlined into the tab, because
 * currentColor does not cross into an SVG loaded through <img>: as files they rendered in
 * one fixed colour and ignored the lit state, so Trade Mode and the other action tabs
 * could not signal anything through them.
 */

const fs = require('fs');
const path = require('path');

/* Shared so a tab can recolour the icon by setting colour, as it does for a glyph. */
const svg = (body) =>
  '<svg viewBox="0 0 24 24" width="19" height="19" fill="none" aria-hidden="true" focusable="false">' +
  body + '</svg>';

/* The riven: two nested triangles, the inner one open at the top, and a point in it.
 *
 * The break is what makes this the riven rune rather than a mark for geometry. The dot is
 * the last triangle, reduced to the one part of it that survives at 19px. */
const rivenRune = svg(
  '<g stroke="currentColor" stroke-width="2.1" stroke-linecap="round" stroke-linejoin="round">' +
    '<path d="M12 3.4 L20 19.6 L4 19.6 Z"/>' +
    '<path d="M12 8.4 L16.4 17.4 L7.6 17.4"/>' +
  '</g>' +
  '<circle cx="12" cy="14.6" r="1.5" fill="currentColor"/>'
);

/* The mod card: a card with an uneven, torn foot.
 *
 * A plain rectangle is a page. The chewed bottom edge is what makes it a Warframe mod, and
 * at this size it does more to identify the object than any interior detail would - the
 * two interior lines of the first pass were invisible at 19px and only muddied the card.
 *
 * Drawn as one closed path rather than four separate strokes. The open version lost its
 * right edge at 19px, because two strokes landing on the same point meet as a hairline
 * join and the box came out looking like a bracket. One path is one shape, so there is no
 * join to get thin, and it is a little heavier than the riven because a card is mostly
 * empty space where the riven is mostly stroke. */
const modCard = svg(
  '<g stroke="currentColor" stroke-width="2.3" stroke-linecap="round" stroke-linejoin="round">' +
    '<path d="M5.4 4.6 H18.6 V15.9 L16.3 18.5 L14.7 17 L12.6 19.3 L10.5 17.5 L8.7 19.1 L5.4 16.2 Z"/>' +
  '</g>'
);

const out = { rivenRune, modCard };

/* Written as a module so dock.js and the preview can share one definition. Writing the
   same markup into two places is how an icon and its tab drift apart. */
const target = path.join(__dirname, '..', 'rail-icons.js');
fs.writeFileSync(target,
  '/* Generated by tools/make-rail-icons.js. Edit that, not this. */\n' +
  'window.OrdisRailIcons = ' + JSON.stringify(out, null, 2) + ';\n');

console.log('wrote rail-icons.js');
console.log('  rivenRune ' + rivenRune.length + ' chars');
console.log('  modCard   ' + modCard.length + ' chars');
